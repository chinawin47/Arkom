using UnityEngine;
using ARKOM.Core;
using ARKOM.Story;
using ARKOM.UI;

[AddComponentMenu("Interactable/Locked Container Proximity Hint")]
public class LockedContainerProximityHint : MonoBehaviour
{
    [Tooltip("Collider ??????????????? (Trigger)")] public Collider triggerZone;
    [Tooltip("????????????????????????????????? (?????????????)")] public string proximityHint = "????????????????";
    [Tooltip("????????????????? (??????)")] public float hintDuration = 3.5f;
    [Tooltip("??????????????????????? GhostSpawn ???? BreakerFail ???????? FindNotes")] public bool restrictToChaseStates = true;
    [Tooltip("??????????? BreakerFailedEvent (?????????????????????????????????) ???????????????????????????")] public bool requireBreakerFailEvent = true;

    private bool shown;
    private bool breakerFailed;

    private void Reset()
    {
        triggerZone = GetComponent<Collider>();
        if (triggerZone) triggerZone.isTrigger = true;
    }

    private void OnEnable()
    {
        EventBus.Subscribe<BreakerFailedEvent>(OnBreakerFailed);
    }
    private void OnDisable()
    {
        EventBus.Unsubscribe<BreakerFailedEvent>(OnBreakerFailed);
    }

    private void OnBreakerFailed(BreakerFailedEvent _)
    {
        breakerFailed = true; // ??????????? / ??????????? chase ????
    }

    private void OnTriggerEnter(Collider other)
    {
        if (shown) return;
        if (!other.CompareTag("Player")) return; // ???????? Tag ???????
        var seq = SequenceController.Instance;
        if (!seq) return;
        if (seq.HasMysteryBoxAttempted) return; // ????????????????? ????????????
        if (requireBreakerFailEvent && !breakerFailed) return; // ??????????????????????? Fail
        if (restrictToChaseStates && seq.CurrentState != SequenceController.StoryState.GhostSpawn && seq.CurrentState != SequenceController.StoryState.BreakerFail) return;
        if (seq.CurrentState == SequenceController.StoryState.FindNotes || seq.CurrentState == SequenceController.StoryState.OpenMysteryBox) return; // ???????????
        if (!string.IsNullOrEmpty(proximityHint)) seq.ShowTempHint(proximityHint, hintDuration);
        shown = true;
    }
}
